"""Справочник ключевых понятий внутренней политики.

Для этих понятий бот отдельно проверяет, упоминаются ли они в тексте Конституции 2026,
и обязательно сообщает об этом (требование п. 4.1 Положения конкурса).
Патерны — регулярные выражения по тексту в нижнем регистре, «ё» заменена на «е».
"""
import re
from dataclasses import dataclass


@dataclass(frozen=True)
class Concept:
    name: str  # как показывать пользователю
    triggers: tuple[str, ...]  # подстроки в вопросе (нижний регистр, без кавычек)
    patterns: tuple[str, ...]  # что искать в тексте Конституции


CONCEPTS: tuple[Concept, ...] = (
    Concept(
        "Закон и Порядок",
        ("закон и порядок", "закона и порядка", "закону и порядку", "заң және тәртіп", "заң мен тәртіп"),
        (r"закон\s+и\s+порядок", r"закона\s+и\s+порядка", r"заң\s+және\s+тәртіп", r"заң\s+мен\s+тәртіп"),
    ),
    Concept(
        "Справедливый Казахстан",
        ("справедливый казахстан", "справедливого казахстана", "справедливому казахстану", "әділетті қазақстан"),
        (r"справедлив\w*\s+казахстан", r"әділетті\s+қазақстан"),
    ),
    Concept(
        "Адал азамат",
        ("адал азамат",),
        (r"адал\s+азамат",),
    ),
    Concept(
        "Таза Қазақстан",
        ("таза қазақстан", "таза казахстан", "чистый казахстан"),
        (r"таза\s+қазақстан", r"таза\s+казахстан", r"чист\w*\s+казахстан"),
    ),
    Concept(
        "Слышащее государство",
        ("слышащее государство", "слышащего государства", "слышащему государству", "есітетін мемлекет"),
        (r"слышащ\w*\s+государств", r"есітетін\s+мемлекет"),
    ),
    Concept(
        "Разные мнения – единая нация",
        ("разные мнения", "әртүрлі пікір"),
        (r"разные\s+мнения", r"әртүрлі\s+пікір"),
    ),
    Concept(
        "Сильный Президент – Влиятельный Парламент – Подотчетное Правительство",
        ("влиятельный парламент", "влиятельного парламента", "сильный президент"),
        (r"влиятельн\w*\s+парламент", r"сильн\w*\s+президент"),
    ),
    Concept(
        "Толық адам",
        ("толық адам", "совершенный человек", "цельная натура"),
        (r"толық\s+адам", r"совершенн\w*\s+человек", r"цельн\w*\s+натур"),
    ),
)


def normalize(text: str) -> str:
    t = text.casefold().replace("ё", "е")
    t = re.sub(r"[«»\"'“”„‘’`]", "", t)
    t = re.sub(r"[–—\-]", " ", t)
    return re.sub(r"\s+", " ", t).strip()


def find_concepts(question: str) -> list[Concept]:
    q = normalize(question)
    return [c for c in CONCEPTS if any(normalize(t) in q for t in c.triggers)]
